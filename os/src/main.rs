// 3. rust_main() 清理 BSS 段
// 4. rust_main() 初始化日志系统
// 5. rust_main() 打印 "Hello, world!"
// 6. rust_main() 打印内存布局信息
// 7. rust_main() 正常退出 QEMU
//
// ===========================================
// Rust 知识补充：
// ===========================================
// 1. 属性（Attribute）
//    - #![...] 是应用于整个 crate 的属性
//    - #[...] 是应用于单个项的属性
//    - deny/warn/allow 控制编译器的检查级别
// 
// 2. no_std 环境
//    - 不能使用标准库（std）
//    - 可以使用核心库（core）
//    - 需要自己实现内存分配、I/O 等功能
// 
// 3. extern "C"
//    - 声明外部符号（可能在汇编或链接器脚本中定义）
//    - "C" 表示使用 C 语言的链接约定
// 
// 4. 裸指针（Raw Pointer）
//    - *mut T: 可变的裸指针
//    - *const T: 不可变的裸指针
//    - 裸指针操作需要 unsafe 块
//    - write_volatile 确保写入不会被优化
// 
// 5. 闭包（Closure）
//    - |a| { ... } 是闭包语法
//    - for_each 使用闭包对每个元素执行操作
// 
// 6. 格式化输出
//    - {:#x} 表示十六进制格式，带 0x 前缀
//    - {:>5} 表示右对齐，宽度 5 个字符
//    - 更多的格式化选项可以参考 Rust 文档
